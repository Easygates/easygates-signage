import type { Scene } from "./signage";
import type { SceneRow } from "@/db/schema";

export function rowToScene(r: SceneRow): Scene {
  return {
    id: r.id,
    name: r.name,
    template: (r.template as Scene["template"]) || "retail-promo",
    eyebrow: r.eyebrow || undefined,
    headline: r.headline || undefined,
    subheadline: r.subheadline || undefined,
    productName: r.productName || undefined,
    description: r.description || undefined,
    originalPrice: r.originalPrice || undefined,
    promoPrice: r.promoPrice || undefined,
    discountBadge: r.discountBadge || undefined,
    ctaText: r.ctaText || undefined,
    tickerText: r.tickerText || undefined,
    imageUrl: r.imageUrl || undefined,
    imageFit: r.imageFit || "cover",
    imagePosition: r.imagePosition || "center",
    videoUrl: r.videoUrl || undefined,
    bgImageUrl: r.bgImageUrl || undefined,
    theme: r.theme || "none",
    bgFrom: r.bgFrom || "#0b1020",
    bgTo: r.bgTo || "#1e2a5a",
    bgAngle: r.bgAngle ?? 135,
    accentColor: r.accentColor || "#ff3b30",
    textColor: r.textColor || "#ffffff",
    mutedColor: r.mutedColor || "#c7cede",
    cardColor: r.cardColor || "#141b33",
    highlightColor: r.highlightColor || undefined,
    animationPreset: (r.animationPreset as Scene["animationPreset"]) || "launch",
    durationSec: r.durationSec ?? 10,
    transition: (r.transition as Scene["transition"]) || "fade",
    staggerMs: r.staggerMs ?? 120,
    kenBurns: (r.kenBurns as Scene["kenBurns"]) || "zoom-in",
    overlayOpacity: r.overlayOpacity ?? 45,
    layoutVariant: r.layoutVariant || "A",
    items: (r.items as Scene["items"]) || null,
    updatedAt: r.updatedAt ? new Date(r.updatedAt).toISOString() : undefined,
  };
}

